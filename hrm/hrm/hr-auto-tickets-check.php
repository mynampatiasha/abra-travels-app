<?php
// =========================================================================
// AUTO TICKET CHECK — Weekly (Friday) + Monthly (last day of month)
// Include this file from header.php so it runs on every login/page load.
// Dedup logic (ref_tag in message) prevents duplicate tickets, same pattern
// as the existing birthday ticket bot.
// =========================================================================

if (!function_exists('runWeeklyMonthlyTicketCheck')) {

function runWeeklyMonthlyTicketCheck($con) {

    // 1. Resolve the system ticket-raiser (Keerti / HR Admin)
    $admin_q = mysqli_query($con, "SELECT id, name FROM hr_employees WHERE email = 'hr-admin@abra-logistic.com' LIMIT 1");
    if (!$admin_q || mysqli_num_rows($admin_q) == 0) {
        error_log("Auto Ticket Check: hr-admin@abra-logistic.com not found in hr_employees");
        return;
    }
    $admin = mysqli_fetch_assoc($admin_q);
    $created_by      = $admin['id'];
    $created_by_name = $admin['name'];

    // 2. Get all active employees
    $emp_q = mysqli_query($con, "SELECT id, employee_id, name FROM hr_employees WHERE LOWER(status) = 'active'");
    if (!$emp_q) return;

    $employees = [];
    while ($r = mysqli_fetch_assoc($emp_q)) {
        $employees[] = $r;
    }
    if (empty($employees)) return;

    $today_dow            = date('N'); // 1 = Mon ... 5 = Fri, 7 = Sun
    $is_last_day_of_month  = (date('j') == date('t'));
    $year     = date('Y');
    $week_num = date('W');
    $month    = date('m');

    foreach ($employees as $emp) {

        // ── WEEKLY — fires every Friday ──────────────────────────────
        if ($today_dow == 5) {
            $ref = "[Auto-Weekly:{$emp['employee_id']}-$year-W$week_num]";
            $chk = mysqli_query($con, "SELECT id FROM tickets WHERE message LIKE '%" . mysqli_real_escape_string($con, $ref) . "%' LIMIT 1");

            if ($chk && mysqli_num_rows($chk) == 0) {
                $subject = "Weekly Review Reminder - {$emp['name']}";
                $message = "Reminder: Your weekly review is scheduled for Saturday.\n\n" .
                           "Please complete:\n" .
                           "- Weekly review (Saturday)\n" .
                           "- Weekly PPT report\n\n" .
                           "Upload your weekly report via the HR Calendar page.\n\n" .
                           "This is an automated notification generated by the HR system.\n\n" .
                           $ref;

                $safe_subject = mysqli_real_escape_string($con, $subject);
                $safe_message = mysqli_real_escape_string($con, $message);
                $deadline     = date('Y-m-d 23:59:59', strtotime('+1 day'));
                $ticket_number = 'WK-' . date('Ymd') . '-' . $emp['employee_id'] . '-' . rand(100, 999);

                $insert_sql = "INSERT INTO tickets
                    (ticket_number, name, subject, message, status, priority, deadline, assigned_to, created_by, created_at, updated_at)
                    VALUES
                    ('$ticket_number', '" . mysqli_real_escape_string($con, $created_by_name) . "', '$safe_subject', '$safe_message', 'Open', 'Medium', '$deadline', '{$emp['id']}', '$created_by', NOW(), NOW())";

                if (mysqli_query($con, $insert_sql)) {
                    error_log("Weekly Auto-Ticket Created: #$ticket_number for {$emp['name']}");
                } else {
                    error_log("Weekly Auto-Ticket Failed for {$emp['name']}: " . mysqli_error($con));
                }
            }
        }

        // ── MONTHLY — fires on last day of month ─────────────────────
        if ($is_last_day_of_month) {
            $ref = "[Auto-Monthly:{$emp['employee_id']}-$year-$month]";
            $chk = mysqli_query($con, "SELECT id FROM tickets WHERE message LIKE '%" . mysqli_real_escape_string($con, $ref) . "%' LIMIT 1");

            if ($chk && mysqli_num_rows($chk) == 0) {
                $subject = "Monthly Calendar & KPI Reminder - {$emp['name']}";
                $message = "Month-end reminder:\n\n" .
                           "- Complete your monthly calendar for the upcoming month\n" .
                           "- Submit your KPI\n" .
                           "- Prepare overall calendar for the month\n\n" .
                           "Upload your monthly calendar via the HR Calendar page.\n\n" .
                           "This is an automated notification generated by the HR system.\n\n" .
                           $ref;

                $safe_subject = mysqli_real_escape_string($con, $subject);
                $safe_message = mysqli_real_escape_string($con, $message);
                $deadline     = date('Y-m-d 23:59:59');
                $ticket_number = 'MN-' . date('Ymd') . '-' . $emp['employee_id'] . '-' . rand(100, 999);

                $insert_sql = "INSERT INTO tickets
                    (ticket_number, name, subject, message, status, priority, deadline, assigned_to, created_by, created_at, updated_at)
                    VALUES
                    ('$ticket_number', '" . mysqli_real_escape_string($con, $created_by_name) . "', '$safe_subject', '$safe_message', 'Open', 'Medium', '$deadline', '{$emp['id']}', '$created_by', NOW(), NOW())";

                if (mysqli_query($con, $insert_sql)) {
                    error_log("Monthly Auto-Ticket Created: #$ticket_number for {$emp['name']}");
                } else {
                    error_log("Monthly Auto-Ticket Failed for {$emp['name']}: " . mysqli_error($con));
                }
            }
        }
    }
}

}

// =========================================================================
// RESOLVE WHICHEVER DB CONNECTION THE INCLUDING PAGE ALREADY HAS
// (the codebase uses both $dbConn from database.php and $con = conexion())
// =========================================================================
if (!isset($__hr_auto_ticket_con) || !$__hr_auto_ticket_con) {
    if (isset($dbConn) && $dbConn) {
        $__hr_auto_ticket_con = $dbConn;
    } elseif (isset($con) && $con) {
        $__hr_auto_ticket_con = $con;
    } elseif (function_exists('conexion')) {
        $__hr_auto_ticket_con = conexion();
    }
}

if (!empty($__hr_auto_ticket_con)) {
    runWeeklyMonthlyTicketCheck($__hr_auto_ticket_con);
}
